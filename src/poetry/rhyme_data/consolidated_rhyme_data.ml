(** {统一接口函数} *)

(** 获取指定韵组的平声字 *)
let get_ping_sheng_chars = function
  | AnRhyme -> AnRhyme.ping_sheng_chars
  | FengRhyme -> FengRhyme.ping_sheng_chars  
  | HuaRhyme -> HuaRhyme.ping_sheng_chars
  | HuiRhyme -> HuiRhyme.ping_sheng_chars
  | JiangRhyme -> JiangRhyme.ping_sheng_chars
  | QuRhyme -> QuRhyme.ping_sheng_chars
  | SiRhyme -> SiRhyme.ping_sheng_chars
  | TianRhyme -> TianRhyme.ping_sheng_chars
  | WangRhyme -> WangRhyme.ping_sheng_chars
  | YuRhyme -> YuRhyme.ping_sheng_chars
  | YueRhyme -> YueRhyme.ping_sheng_chars
  | XueRhyme -> [] (* 雪韵组数据待补充 *)
  | UnknownRhyme -> [] (* 未知韵组无数据 *)

(** 获取指定韵组的仄声字 *)
let get_ze_sheng_chars = function
  | AnRhyme -> AnRhyme.ze_sheng_chars
  | FengRhyme -> FengRhyme.ze_sheng_chars
  | HuaRhyme -> HuaRhyme.ze_sheng_chars
  | HuiRhyme -> HuiRhyme.ze_sheng_chars
  | JiangRhyme -> JiangRhyme.ze_sheng_chars
  | QuRhyme -> QuRhyme.ze_sheng_chars
  | SiRhyme -> SiRhyme.ze_sheng_chars
  | TianRhyme -> TianRhyme.ze_sheng_chars
  | WangRhyme -> WangRhyme.ze_sheng_chars
  | YuRhyme -> YuRhyme.ze_sheng_chars
  | YueRhyme -> YueRhyme.ze_sheng_chars
  | XueRhyme -> [] (* 雪韵组数据待补充 *)
  | UnknownRhyme -> [] (* 未知韵组无数据 *)

(** 获取所有韵组列表 *)
let get_all_rhyme_groups () = [
  AnRhyme; FengRhyme; HuaRhyme; HuiRhyme; JiangRhyme;
  QuRhyme; SiRhyme; TianRhyme; WangRhyme; YuRhyme; YueRhyme
]

(** 获取所有韵字数据 *)
let get_all_rhyme_data () =
  let groups = get_all_rhyme_groups () in
  List.map (fun group -> 
    (group, get_ping_sheng_chars group, get_ze_sheng_chars group)
  ) groups

(** 韵组名称转换 *)
