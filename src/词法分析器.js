const { 位置, 词法错误, 词元类型, 词元, 带位置词元, 词元工厂 } = require('./词法令牌');

/**
 * 词法分析器状态类
 */
class 词法分析器状态 {
    constructor(输入, 文件名) {
        this.输入 = 输入 || '';
        this.文件名 = 文件名 || '';
        this.位置 = 0;
        this.长度 = this.输入.length;
        this.当前行号 = 1;
        this.当前列号 = 1;
    }

    /**
     * 获取当前字符
     */
    获取当前字符() {
        if (this.位置 >= this.长度) {
            return null;
        }
        return this.输入[this.位置];
    }

    /**
     * 前进一个字符
     */
    前进() {
        if (this.位置 < this.长度) {
            const 当前字符 = this.输入[this.位置];
            this.位置++;
            if (当前字符 === '\n') {
                this.当前行号++;
                this.当前列号 = 1;
            } else {
                this.当前列号++;
            }
        }
        return this;
    }

    /**
     * 获取当前位置信息
     */
    获取当前位置() {
        return new 位置(this.当前行号, this.当前列号, this.文件名);
    }

    /**
     * 查看前方字符而不移动位置
     */
    预览字符(偏移量 = 0) {
        const 目标位置 = this.位置 + 偏移量;
        if (目标位置 >= this.长度) {
            return null;
        }
        return this.输入[目标位置];
    }

    /**
     * 跳过空白字符
     */
    跳过空白字符() {
        while (this.位置 < this.长度) {
            const 字符 = this.输入[this.位置];
            if (字符 === ' ' || 字符 === '\t' || 字符 === '\r') {
                this.前进();
            } else {
                break;
            }
        }
        return this;
    }

    /**
     * 检查是否到达文件末尾
     */
    是否结束() {
        return this.位置 >= this.长度;
    }
}

