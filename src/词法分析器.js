/**
 * 词法分析器主类
 */
class 词法分析器 {
    constructor(输入, 文件名 = '') {
        this.状态 = new 词法分析器状态(输入, 文件名);
    }

    /**
     * 判断字符是否为中文字符
     */
    是否为中文字符(字符) {
        if (!字符) return false;
        const 编码 = 字符.charCodeAt(0);
        return (编码 >= 0x4e00 && 编码 <= 0x9fff) || // 基本汉字
               (编码 >= 0x3400 && 编码 <= 0x4dbf) || // 扩展A
               (编码 >= 0x20000 && 编码 <= 0x2a6df); // 扩展B
    }

    /**
     * 判断字符是否为数字
     */
    是否为阿拉伯数字(字符) {
        return 字符 >= '0' && 字符 <= '9';
    }

    /**
     * 判断字符是否为中文数字
     */
    是否为中文数字(字符) {
        return 中文数字映射.has(字符);
    }

    /**
     * 读取字符串字面量 (『...』)
     */
    读取字符串字面量() {
        const 起始位置 = this.状态.获取当前位置();
        this.状态.前进(); // 跳过开始的『
        
        let 字符串值 = '';
        
        while (!this.状态.是否结束()) {
            const 字符 = this.状态.获取当前字符();
            
            if (字符 === '』') {
                this.状态.前进(); // 跳过结束的』
                return 词元工厂.创建字符串词元(字符串值, 起始位置);
            }
            
            if (字符 === '\n') {
                throw new 词法错误('字符串字面量不能包含换行符', this.状态.获取当前位置());
            }
            
            字符串值 += 字符;
            this.状态.前进();
        }
        
        throw new 词法错误('未闭合的字符串字面量', 起始位置);
    }

    /**
     * 读取引用标识符 (「...」)
     */
    读取引用标识符() {
        const 起始位置 = this.状态.获取当前位置();
        this.状态.前进(); // 跳过开始的「
        
        let 标识符值 = '';
        
        while (!this.状态.是否结束()) {
            const 字符 = this.状态.获取当前字符();
            
            if (字符 === '」') {
                this.状态.前进(); // 跳过结束的」
                if (标识符值.trim() === '') {
                    throw new 词法错误('引用标识符不能为空', 起始位置);
                }
                return 词元工厂.创建引用标识符词元(标识符值, 起始位置);
            }
            
            if (字符 === '\n') {
                throw new 词法错误('引用标识符不能包含换行符', this.状态.获取当前位置());
            }
            
            标识符值 += 字符;
            this.状态.前进();
        }
        
        throw new 词法错误('未闭合的引用标识符', 起始位置);
    }

    /**
     * 读取中文数字序列
     */
    读取中文数字序列() {
        const 起始位置 = this.状态.获取当前位置();
        let 数字序列 = '';
        
        while (!this.状态.是否结束()) {
            const 字符 = this.状态.获取当前字符();
            
            if (this.是否为中文数字(字符)) {
                数字序列 += 字符;
                this.状态.前进();
            } else {
                break;
            }
        }
        
        if (数字序列 === '') {
            throw new 词法错误('期望中文数字', 起始位置);
        }
        
        return 词元工厂.创建中文数字词元(数字序列, 起始位置);
    }

    /**
     * 读取阿拉伯数字 (但要报错，因为已禁用)
     */
    读取阿拉伯数字() {
        const 起始位置 = this.状态.获取当前位置();
        throw new 词法错误('阿拉伯数字已禁用，请使用中文数字', 起始位置);
    }

    /**
     * 读取中文关键字或标识符
     */
    读取中文词汇() {
        const 起始位置 = this.状态.获取当前位置();
        let 词汇 = '';
        
        // 读取连续的中文字符
        while (!this.状态.是否结束()) {
            const 字符 = this.状态.获取当前字符();
            
            if (this.是否为中文字符(字符)) {
                词汇 += 字符;
                this.状态.前进();
            } else {
                break;
            }
        }
        
        if (词汇 === '') {
            throw new 词法错误('期望中文字符', 起始位置);
        }
        
        // 检查是否为关键字
        if (中文关键字映射.has(词汇)) {
            const 关键字类型 = 中文关键字映射.get(词汇);
            return 词元工厂.创建关键字词元(关键字类型, 起始位置);
        }
        
        // 否则作为特殊标识符处理
        return new 词元(词元类型.特殊标识符令牌, 词汇, 起始位置);
    }

    /**
     * 获取下一个词元
     */
    获取下一个词元() {
        // 跳过空白字符
        this.状态.跳过空白字符();
        
        if (this.状态.是否结束()) {
            return 词元工厂.创建特殊词元(词元类型.文件结束, this.状态.获取当前位置());
        }
        
        const 字符 = this.状态.获取当前字符();
        const 当前位置 = this.状态.获取当前位置();
        
        // 处理换行符
        if (字符 === '\n') {
            this.状态.前进();
            return 词元工厂.创建特殊词元(词元类型.换行符, 当前位置);
        }
        
        // 处理字符串字面量
        if (字符 === '『') {
            return this.读取字符串字面量();
        }
        
        // 处理引用标识符
        if (字符 === '「') {
            return this.读取引用标识符();
        }
        
        // 处理中文标点符号
        if (中文标点符号映射.has(字符)) {
            const 标点类型 = 中文标点符号映射.get(字符);
            this.状态.前进();
            return 词元工厂.创建标点符号词元(标点类型, 当前位置);
        }
        
        // 处理阿拉伯数字 (报错)
        if (this.是否为阿拉伯数字(字符)) {
            return this.读取阿拉伯数字();
        }
        
        // 处理中文数字
        if (this.是否为中文数字(字符)) {
            return this.读取中文数字序列();
        }
        
        // 处理中文字符 (关键字或标识符)
        if (this.是否为中文字符(字符)) {
            return this.读取中文词汇();
        }
        
        // 处理ASCII字符 (全部禁用)
        if (字符.charCodeAt(0) < 128) {
            throw new 词法错误(`ASCII字符已禁用，请使用中文标点符号。禁用字符: ${字符}`, 当前位置);
        }
        
        // 未知字符
        throw new 词法错误(`意外的字符: ${字符}`, 当前位置);
    }

    /**
     * 词法分析主函数 - 返回所有词元
     */
    词法分析() {
        const 词元列表 = [];
        
        try {
            while (true) {
                const 词元 = this.获取下一个词元();
                const 带位置词元实例 = new 带位置词元(词元, 词元.位置 || this.状态.获取当前位置());
                词元列表.push(带位置词元实例);
                
                if (词元.类型 === 词元类型.文件结束) {
                    break;
                }
            }
        } catch (错误) {
            if (错误.name === '词法错误') {
                throw 错误;
            } else {
                throw new 词法错误(`词法分析过程中发生未知错误: ${错误.message}`, this.状态.获取当前位置());
            }
        }
        
        return 词元列表;
    }

    /**
     * 查找关键字 - 静态方法
     */
    static 查找关键字(词汇) {
        return 中文关键字映射.get(词汇) || null;
    }
}

