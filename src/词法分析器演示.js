const { 词法分析器 } = require('./词法分析器');

/**
 * 演示词法分析器功能
 */
function 演示词法分析器() {
    console.log('🔤 骆言词法分析器 - JavaScript版本演示');
    console.log('═'.repeat(50));
    
    // 测试用例列表
    const 测试用例 = [
        {
            名称: '基本关键字',
            代码: '让 如果 那么 否则'
        },
        {
            名称: '中文标点符号',
            代码: '（）【】，；：｜→＝'
        },
        {
            名称: '字符串字面量',
            代码: '『这是一个字符串』'
        },
        {
            名称: '引用标识符',
            代码: '「变量名」「函数名」'
        },
        {
            名称: '中文数字',
            代码: '一二三 五六七'
        },
        {
            名称: '复合表达式',
            代码: '让「结果」＝『计算完成』'
        },
        {  
            名称: '多行代码',
            代码: '让「数值」＝一二三\n如果「数值」那么『真』'
        }
    ];
    
    // 逐个测试
    测试用例.forEach((用例, 索引) => {
        console.log(`\n${索引 + 1}. ${用例.名称}:`);
        console.log(`   输入: ${用例.代码.replace(/\n/g, '\\n')}`);
        
        try {
            const 分析器 = new 词法分析器(用例.代码, `demo${索引 + 1}.ly`);
            const 词元列表 = 分析器.词法分析();
            
            console.log(`   词元数: ${词元列表.length}`);
            console.log('   词元列表:');
            
            词元列表.forEach((带位置词元, 位置) => {
                const 词元 = 带位置词元.词元;
                const 位置信息 = 带位置词元.位置;
                
                if (词元.类型 !== '文件结束' && 词元.类型 !== 'EOF') {
                    const 位置字符串 = `[${位置信息.行号}:${位置信息.列号}]`;
                    console.log(`     ${位置字符串} ${词元.toString()}`);
                }
            });
            
        } catch (错误) {
            console.log(`   ❌ 错误: ${错误.message}`);
        }
    });
    
    // 错误处理演示
    console.log('\n🚨 错误处理演示:');
    console.log('═'.repeat(30));
    
    const 错误用例 = [
        {
            名称: 'ASCII字符禁用',
            代码: 'hello world'
        },
        {
            名称: '阿拉伯数字禁用', 
            代码: '123 + 456'
        },
        {
            名称: '未闭合字符串',
            代码: '『未闭合的字符串'
        }
    ];
    
    错误用例.forEach((用例, 索引) => {
        console.log(`\n${索引 + 1}. ${用例.名称}:`);
        console.log(`   输入: ${用例.代码}`);
        
        try {
            const 分析器 = new 词法分析器(用例.代码);
            分析器.词法分析();
            console.log('   ⚠️  意外: 未产生错误');
        } catch (错误) {
            console.log(`   ✅ 预期错误: ${错误.message}`);
        }
    });
    
    console.log('\n✅ Phase 2 词法分析器转换完成!');
    console.log('支持完整的中文编程语法词法分析');
    console.log('🎯 准备开始 Phase 3: 语法分析器转换');
}

// 如果直接运行此文件，则执行演示
if (require.main === module) {
    演示词法分析器();
}

module.exports = { 演示词法分析器 };